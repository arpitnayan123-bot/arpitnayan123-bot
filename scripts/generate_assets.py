#!/usr/bin/env python3
"""
Generate the animated SVG assets used by the GitHub profile README.

Everything the profile shows as a custom visual (hero header, typing
animation, developer terminal, footer banner, section divider) is built
here from a single design system so colours, typography and motion stay
consistent across the whole profile.

Design system
-------------
- Backgrounds : deep midnight navy (#0A0E1A) and charcoal panel (#0D1117)
- Accents     : electric blue (#1F6FEB / #58A6FF), restrained violet (#8B5CF6 / #A371F7)
- Text        : #E6EDF3 (primary), #8B949E (muted), #6E7681 (faint)
- Typography  : system monospace stack (no webfonts - GitHub <img> SVGs
                cannot load external fonts)
- Motion      : SMIL animations only (no CSS keyframes needed, no JS -
                GitHub sanitises scripts and SMIL renders inside <img>)

GitHub compatibility notes
--------------------------
* Every animated element keeps full-content initial attributes, so if a
  renderer ignores SMIL the SVG still shows the complete static content.
* No external URLs are referenced from inside the SVGs.
* The typing animation reveals phrases with an animated clip-path rect;
  the terminal types commands the same way, with a blinking block cursor.

Usage
-----
    python3 scripts/generate_assets.py

Outputs are written to assets/ . Edit the constants below (or the phrase /
terminal content lists) and re-run to refresh the visuals.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"

# ----------------------------------------------------------------------------
# Design tokens
# ----------------------------------------------------------------------------
BG_DEEP = "#0A0E1A"      # midnight navy
BG_PANEL = "#0D1117"     # charcoal panel
STROKE = "#263048"       # subtle border
BLUE = "#1F6FEB"         # electric blue
BLUE_LT = "#58A6FF"      # light blue
VIOLET = "#8B5CF6"       # restrained violet
VIOLET_LT = "#A371F7"    # light violet
TEXT = "#E6EDF3"         # primary text
TEXT_SOFT = "#C9D1D9"    # secondary text
MUTED = "#8B949E"        # muted text
FAINT = "#6E7681"        # faint text
SUBTITLE = "#A5B4D6"     # header subtitle

MONO = "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace"

GENERATED_NOTE = (
    "<!-- Generated by scripts/generate_assets.py - edit the script and "
    "re-run instead of editing this file. See ASSETS.md. -->"
)

# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------


def wave_path(
    width: int, baseline: float, amplitude: float, period: float, bottom: float = None
) -> str:
    """Build a seamless horizontal wave path spanning 2 * width.

    The path starts and ends on the baseline, so a copy shifted by exactly
    `width` tiles seamlessly; animating translate from 0 to -width gives an
    endless wave. IMPORTANT: `period` must divide `width` exactly, otherwise
    the loop visibly jumps. The curve is closed down to `bottom`
    (default: baseline + amplitude * 4) so the shape can be filled solid.
    """
    span = width * 2
    half = period / 2.0
    if bottom is None:
        bottom = baseline + amplitude * 4
    d = [f"M0 {baseline:.1f}"]
    x = 0.0
    up = True
    while x < span:
        cx1, cx2 = x + half / 3.0, x + half * 2.0 / 3.0
        dy = -amplitude if up else amplitude
        d.append(f"C{cx1:.1f} {baseline + dy:.1f},{cx2:.1f} {baseline + dy:.1f},{x + half:.1f} {baseline:.1f}")
        x += half
        up = not up
    d.append(f"L{span:.1f} {bottom:.1f} L0 {bottom:.1f} Z")
    return " ".join(d)


def wave_layer(
    path_d: str, width: int, dur: str, grad_id: str, opacity: float, direction: int = 1
) -> str:
    """One translated wave <g> with a seamless SMIL loop."""
    frm = "0 0" if direction > 0 else f"{-width} 0"
    to = f"{-width} 0" if direction > 0 else "0 0"
    return (
        f'<g opacity="{opacity}">'
        f'<path d="{path_d}" fill="url(#{grad_id})">'
        f'<animateTransform attributeName="transform" attributeType="XML" '
        f'type="translate" from="{frm}" to="{to}" dur="{dur}" '
        f'repeatCount="indefinite"/>'
        f"</path></g>"
    )


def lin_grad(grad_id: str, stops, x1="0%", y1="0%", x2="100%", y2="0%") -> str:
    parts = []
    for s in stops:
        off, col = s[0], s[1]
        op = s[2] if len(s) > 2 else None
        stop = f'<stop offset="{off}" stop-color="{col}"'
        if op is not None:
            stop += f' stop-opacity="{op}"'
        parts.append(stop + "/>")
    body = "".join(parts)
    return (
        f'<linearGradient id="{grad_id}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{body}</linearGradient>'
    )


# ----------------------------------------------------------------------------
# 1. Hero header
# ----------------------------------------------------------------------------

NAME = "ARPIT NAYAN"
TAGLINE = "AI Builder \u00b7 Aspiring Founder \u00b7 IIT Student"
EYEBROW = "// building in public"

W, H = 896, 260


def header_svg(
    width: int = 896,
    height: int = 260,
    name_fs: int = 46,
    tag_fs: float = 15,
    eye_fs: float = 11.5,
) -> str:
    W, H = width, height
    cx = W / 2
    name_y = int(H * 0.485)
    bar_y = name_y + 14
    tag_y = bar_y + 28
    eye_y = name_y - 50
    glow_cy = int(H * 0.42)
    # periods must divide W for seamless loops
    p_back = W // 2
    p_front = W // 4
    p_slow = W
    wave_back = wave_path(W, H - 64, 20, p_back)
    wave_front = wave_path(W, H - 46, 16, p_front)
    # third slow decorative wave, drawn under the two main ones
    wave_slow = wave_path(W, H - 78, 12, p_slow)

    dots = (
        f'<pattern id="dotgrid" width="28" height="28" patternUnits="userSpaceOnUse">'
        f'<circle cx="2" cy="2" r="1.1" fill="{BLUE_LT}" opacity="0.05"/></pattern>'
    )
    glow = (
        f'<radialGradient id="glow" cx="50%" cy="42%" r="55%">'
        f'<stop offset="0%" stop-color="{VIOLET}" stop-opacity="0.16"/>'
        f'<stop offset="55%" stop-color="{BLUE}" stop-opacity="0.07"/>'
        f'<stop offset="100%" stop-color="{BLUE}" stop-opacity="0"/></radialGradient>'
    )
    bar_w = 120 if W >= 800 else 96

    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-label="Arpit Nayan - AI Builder, Aspiring Founder, IIT Student">
  <defs>
    {dots}
    {glow}
    {lin_grad("wg1", [(0, BLUE, 0.32), (0.5, "#4C6FFF", 0.30), (1, VIOLET, 0.32)])}
    {lin_grad("wg2", [(0, VIOLET, 0.55), (0.55, "#5A7CFF", 0.50), (1, BLUE, 0.55)])}
    {lin_grad("wg3", [(0, BLUE, 0.16), (1, VIOLET, 0.16)])}
    {lin_grad("bar", [(0, BLUE_LT), (1, VIOLET_LT)])}
  </defs>

  <rect width="{W}" height="{H}" fill="{BG_DEEP}"/>
  <rect width="{W}" height="{H}" fill="url(#dotgrid)"/>
  <ellipse cx="{cx}" cy="{glow_cy}" rx="{int(W * 0.42)}" ry="{int(H * 0.44)}" fill="url(#glow)"/>

  {wave_layer(wave_slow, W, "21s", "wg3", 1.0)}
  {wave_layer(wave_back, W, "14s", "wg1", 1.0)}
  {wave_layer(wave_front, W, "9s", "wg2", 1.0)}

  <text x="{cx}" y="{eye_y}" text-anchor="middle" font-family="{MONO}" font-size="{eye_fs}"
        letter-spacing="2.5" fill="{FAINT}">{EYEBROW}</text>

  <text x="{cx}" y="{name_y}" text-anchor="middle" font-family="{MONO}" font-size="{name_fs}"
        font-weight="700" letter-spacing="6" fill="#F0F6FC">{NAME}</text>

  <rect x="{cx - bar_w / 2}" y="{bar_y}" width="{bar_w}" height="2.6" rx="1.3" fill="url(#bar)"/>

  <text x="{cx}" y="{tag_y}" text-anchor="middle" font-family="{MONO}" font-size="{tag_fs}"
        letter-spacing="2" fill="{SUBTITLE}">{TAGLINE}</text>
</svg>
"""


# ----------------------------------------------------------------------------
# 2. Typing animation
# ----------------------------------------------------------------------------

PHRASES = [
    "Building AI-powered products",
    "Exploring autonomous coding agents",
    "Developing healthcare intelligence",
    "Engineering software systems",
    "Learning and building as an aspiring founder",
]

TW, TH = 600, 56
T_FS = 20
CHAR_W = 12.0          # monospace advance width at 20px
HOLD = 1.7             # seconds each phrase stays fully visible


def typing_svg() -> str:
    slots = []
    for p in PHRASES:
        t_in = min(2.4, max(1.0, len(p) * 0.048))
        t_out = min(t_in, 1.0)
        slots.append((p, t_in, t_out))
    total = sum(t + HOLD + o for _, t, o in slots)

    groups, clips = [], []
    cursor = 0.0
    for i, (phrase, t_in, t_out) in enumerate(slots):
        w = len(phrase) * CHAR_W + 10
        x = (TW - w) / 2.0
        f0 = cursor / total
        f1 = (cursor + t_in) / total
        f2 = (cursor + t_in + HOLD) / total
        f3 = (cursor + t_in + HOLD + t_out) / total
        # strictly increasing keyTimes, clamped to [0, 1]
        f1, f2, f3 = min(f1, 0.999), min(f2, 0.9995), min(f3, 0.9999)
        keytimes = f"0;{f0:.4f};{f1:.4f};{f2:.4f};{f3:.4f};1"
        initial = w if i == 0 else 0  # static fallback shows the first phrase
        clips.append(
            f'  <clipPath id="tp{i}"><rect x="{x:.1f}" y="6" width="{initial:.1f}" height="44">'
            f'<animate attributeName="width" calcMode="linear" '
            f'values="0;0;{w:.1f};{w:.1f};0;0" keyTimes="{keytimes}" '
            f'dur="{total:.2f}s" repeatCount="indefinite"/></rect></clipPath>'
        )
        groups.append(
            f'  <g clip-path="url(#tp{i})">'
            f'<text x="{TW / 2:.0f}" y="35" text-anchor="middle" font-family="{MONO}" '
            f'font-size="{T_FS}" font-weight="600" letter-spacing="0.5" '
            f'class="tp">{escape(phrase)}</text></g>'
        )
        cursor += t_in + HOLD + t_out

    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{TW}" height="{TH}" viewBox="0 0 {TW} {TH}" role="img" aria-label="Rotating phrases: {', '.join(PHRASES)}">
  <style>.tp{{fill:#1F6FEB}} @media (prefers-color-scheme:dark) {{.tp{{fill:#7CB0FF}}}}</style>
  <defs>
{chr(10).join(clips)}
  </defs>
{chr(10).join(groups)}
</svg>
"""


def escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ----------------------------------------------------------------------------
# 3. Developer terminal
# ----------------------------------------------------------------------------

TERMINAL_TITLE = "arpit@iitj \u2014 ~/profile"
TTW, TTH = 896, 244
T_FS = 13
LINE_H = 21.5
T_X = 26
T_Y0 = 66

# (prompt-command, output-tspans) — outputs are lists of (text, fill) spans
TERMINAL_LINES = [
    ("whoami", [("Arpit Nayan", VIOLET_LT)]),
    (
        "interests",
        [
            ("AI", BLUE_LT),
            (" | ", "#3D4660"),
            ("Healthcare", VIOLET_LT),
            (" | ", "#3D4660"),
            ("Software Engineering", TEXT_SOFT),
        ],
    ),
    ("exploring", [("Autonomous ", TEXT_SOFT), ("Coding Agents", BLUE_LT)]),
    ("building", [("Healthcare Intelligence", BLUE_LT), (" Systems", TEXT_SOFT)]),
]


def terminal_svg() -> str:
    n_lines = len(TERMINAL_LINES) * 2 + 1  # 4 cmd + 4 out + 1 prompt cursor line
    content_h = n_lines * LINE_H + 14
    body_h = max(int(T_Y0 + content_h), 150)
    h = body_h + 6

    total = 11.6  # master loop seconds
    type_t = 0.62
    step = total / len(TERMINAL_LINES)

    clips, groups = [], []
    y = T_Y0
    for i, (cmd, out) in enumerate(TERMINAL_LINES):
        cmd_w = (len(cmd) + 2) * T_FS * 0.6
        f0 = (i * step) / total
        f1 = (i * step + type_t) / total
        keytimes = f"0;{f0:.4f};{f1:.4f};1"
        clips.append(
            f'  <clipPath id="tc{i}"><rect x="{T_X - 2}" y="{y - T_FS:.1f}" width="{cmd_w + 6:.1f}" height="20">'
            f'<animate attributeName="width" calcMode="linear" values="0;0;{cmd_w + 6:.1f};{cmd_w + 6:.1f}" '
            f'keyTimes="{keytimes}" dur="{total}s" repeatCount="indefinite"/></rect></clipPath>'
        )
        groups.append(
            f'  <g clip-path="url(#tc{i})"><text x="{T_X}" y="{y:.1f}" font-family="{MONO}" '
            f'font-size="{T_FS}"><tspan fill="{BLUE_LT}">$</tspan>'
            f'<tspan fill="{TEXT}" dx="7">{escape(cmd)}</tspan></text></g>'
        )
        y += LINE_H
        fa = (i * step + type_t + 0.12) / total
        spans = "".join(f'<tspan fill="{fill}">{escape(t)}</tspan>' for t, fill in out)
        groups.append(
            f'  <g><text x="{T_X}" y="{y:.1f}" font-family="{MONO}" font-size="{T_FS}" '
            f'opacity="1"><animate attributeName="opacity" calcMode="discrete" '
            f'values="0;0;1;1" keyTimes="0;{fa:.4f};{min(fa + 0.002, 0.9999):.4f};1" '
            f'dur="{total}s" repeatCount="indefinite"/>{spans}</text></g>'
        )
        y += LINE_H

    prompt_y = y
    # fade the whole session out just before the loop restarts
    session_fade = (
        f'  <animate attributeName="opacity" calcMode="linear" '
        f'values="1;1;0" keyTimes="0;0.96;1" dur="{total}s" repeatCount="indefinite"/>'
    )
    prompt_cursor = (
        f'  <text x="{T_X}" y="{prompt_y:.1f}" font-family="{MONO}" font-size="{T_FS}">'
        f'<tspan fill="{BLUE_LT}">$</tspan></text>'
        f'  <rect x="{T_X + 16}" y="{prompt_y - 12:.1f}" width="8" height="14" fill="{BLUE_LT}">'
        f'<animate attributeName="opacity" values="1;0" calcMode="discrete" '
        f'dur="1.1s" repeatCount="indefinite"/></rect>'
    )

    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{TTW}" height="{h}" viewBox="0 0 {TTW} {h}" role="img" aria-label="Terminal: whoami - Arpit Nayan; interests - AI, Healthcare, Software Engineering; exploring - Autonomous Coding Agents; building - Healthcare Intelligence Systems">
  <defs>
    {lin_grad("thead", [(0, "#111A2E"), (1, "#0D1424")])}
  </defs>

  <rect x="1" y="1" width="{TTW - 2}" height="{h - 2}" rx="14" fill="{BG_PANEL}" stroke="{STROKE}" stroke-width="1.5"/>
  <rect x="1.75" y="1.75" width="{TTW - 3.5}" height="43" rx="13" fill="url(#thead)"/>
  <rect x="1.75" y="24" width="{TTW - 3.5}" height="20" fill="url(#thead)"/>
  <circle cx="28" cy="23" r="6" fill="#FF5F57" opacity="0.92"/>
  <circle cx="50" cy="23" r="6" fill="#FEBC2E" opacity="0.92"/>
  <circle cx="72" cy="23" r="6" fill="#28C840" opacity="0.92"/>
  <text x="{TTW / 2}" y="27.5" text-anchor="middle" font-family="{MONO}" font-size="11.5" fill="{FAINT}">{escape(TERMINAL_TITLE)}</text>
  <line x1="1" y1="44" x2="{TTW - 1}" y2="44" stroke="{STROKE}" stroke-width="1"/>

<g opacity="1">
  {session_fade}
{chr(10).join(groups)}
{prompt_cursor}
</g>
</svg>
"""


# ----------------------------------------------------------------------------
# main
# ----------------------------------------------------------------------------

FILES = {
    # desktop variants
    "header-hero.svg": lambda: header_svg(),
    "typing.svg": typing_svg,
    "terminal.svg": terminal_svg,
}


def main() -> None:
    ASSETS.mkdir(exist_ok=True)
    for name, fn in FILES.items():
        svg = fn()
        (ASSETS / name).write_text(svg, encoding="utf-8")
        print(f"wrote  assets/{name:20} {len(svg):6d} bytes")


if __name__ == "__main__":
    main()
