#!/usr/bin/env python3
"""
Generate the vector SMIL assets used by the GitHub profile README.

The text-critical animations - the typing strip, the developer terminal and
the section divider - are built here as SMIL SVGs: vectors keep text crisp,
SMIL renders inside GitHub's sanitised <img> pipeline, and every element
keeps full-content initial attributes so the SVGs degrade to complete
static images when animation is ignored.

The ambient full-width visuals (aurora hero, nebula footer) are rendered as
looping GIFs by scripts/generate_gifs.py, which shares this design system.

Design system
-------------
- Backgrounds : aubergine-charcoal panels (#110E19)
- Accents     : signature gold (#FFC93C / #FFE29A), amber (#FFB454),
                warm orange (#FF8C42)
- Secondary   : restrained violet (#8B5CF6 / #A78BFA) for contrast moments
- Text        : #F2E9D8 (primary), #D9CDB4 (secondary), #96886F (faint)
- Typography  : system monospace stack (no webfonts - GitHub <img> SVGs
                cannot load external fonts)
- Motion      : SMIL animations only (no CSS keyframes needed, no JS)

GitHub compatibility notes
--------------------------
* Every animated element keeps full-content initial attributes, so if a
  renderer ignores SMIL the SVG still shows the complete static content.
* No external URLs are referenced from inside the SVGs.
* The typing animation reveals phrases with an animated clip-path rect;
  the terminal types commands the same way, with a blinking block cursor.

Usage
-----
    python3 scripts/generate_assets.py

Outputs are written to assets/ . Edit the constants below (or the phrase /
terminal content lists) and re-run to refresh the visuals.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"

# ----------------------------------------------------------------------------
# Design tokens
# ----------------------------------------------------------------------------

BG_PANEL = "#110E19"     # aubergine-charcoal panel
STROKE = "#2E2740"       # warm subtle border
GOLD = "#FFC93C"         # signature gold
GOLD_LT = "#FFE29A"      # light gold
AMBER = "#FFB454"        # amber
ORANGE = "#FF8C42"       # warm orange
VIOLET = "#8B5CF6"       # restrained violet
VIOLET_LT = "#A78BFA"    # light violet
TEXT = "#F2E9D8"         # warm primary text
TEXT_SOFT = "#D9CDB4"    # warm secondary text
FAINT = "#96886F"        # warm faint text

MONO = "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace"

GENERATED_NOTE = (
    "<!-- Generated by scripts/generate_assets.py - edit the script and "
    "re-run instead of editing this file. See ASSETS.md. -->"
)

# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------

def lin_grad(grad_id: str, stops, x1="0%", y1="0%", x2="100%", y2="0%") -> str:
    parts = []
    for s in stops:
        off, col = s[0], s[1]
        op = s[2] if len(s) > 2 else None
        stop = f'<stop offset="{off}" stop-color="{col}"'
        if op is not None:
            stop += f' stop-opacity="{op}"'
        parts.append(stop + "/>")
    body = "".join(parts)
    return (
        f'<linearGradient id="{grad_id}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{body}</linearGradient>'
    )


# ----------------------------------------------------------------------------
# 1. Typing animation
# ----------------------------------------------------------------------------

PHRASES = [
    "Building AI-powered products",
    "Exploring autonomous coding agents",
    "Developing healthcare intelligence",
    "Engineering software systems",
    "Learning and building as an aspiring founder",
]

TW, TH = 600, 56
T_FS = 20
CHAR_W = 12.0          # monospace advance width at 20px
HOLD = 1.7             # seconds each phrase stays fully visible


def typing_svg() -> str:
    slots = []
    for p in PHRASES:
        t_in = min(2.4, max(1.0, len(p) * 0.048))
        t_out = min(t_in, 1.0)
        slots.append((p, t_in, t_out))
    total = sum(t + HOLD + o for _, t, o in slots)

    groups, clips = [], []
    cursor = 0.0
    for i, (phrase, t_in, t_out) in enumerate(slots):
        w = len(phrase) * CHAR_W + 10
        x = (TW - w) / 2.0
        f0 = cursor / total
        f1 = (cursor + t_in) / total
        f2 = (cursor + t_in + HOLD) / total
        f3 = (cursor + t_in + HOLD + t_out) / total
        # strictly increasing keyTimes, clamped to [0, 1]
        f1, f2, f3 = min(f1, 0.999), min(f2, 0.9995), min(f3, 0.9999)
        keytimes = f"0;{f0:.4f};{f1:.4f};{f2:.4f};{f3:.4f};1"
        initial = w if i == 0 else 0  # static fallback shows the first phrase
        clips.append(
            f'  <clipPath id="tp{i}"><rect x="{x:.1f}" y="6" width="{initial:.1f}" height="44">'
            f'<animate attributeName="width" calcMode="linear" '
            f'values="0;0;{w:.1f};{w:.1f};0;0" keyTimes="{keytimes}" '
            f'dur="{total:.2f}s" repeatCount="indefinite"/></rect></clipPath>'
        )
        groups.append(
            f'  <g clip-path="url(#tp{i})">'
            f'<text x="{TW / 2:.0f}" y="35" text-anchor="middle" font-family="{MONO}" '
            f'font-size="{T_FS}" font-weight="600" letter-spacing="0.5" '
            f'class="tp">{escape(phrase)}</text></g>'
        )
        cursor += t_in + HOLD + t_out

    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{TW}" height="{TH}" viewBox="0 0 {TW} {TH}" role="img" aria-label="Rotating phrases: {', '.join(PHRASES)}">
  <style>.tp{{fill:#B26B00}} @media (prefers-color-scheme:dark) {{.tp{{fill:#FFD24A}}}}</style>
  <defs>
{chr(10).join(clips)}
  </defs>
{chr(10).join(groups)}
</svg>
"""


def escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

# ----------------------------------------------------------------------------
# 2. Developer terminal
# ----------------------------------------------------------------------------

TERMINAL_TITLE = "arpit@iitj \u2014 ~/profile"
TTW, TTH = 896, 244
T_FS = 13
LINE_H = 21.5
T_X = 26
T_Y0 = 66

# (prompt-command, output-tspans) — outputs are lists of (text, fill) spans
TERMINAL_LINES = [
    ("whoami", [("Arpit Nayan", GOLD_LT)]),
    (
        "interests",
        [
            ("AI", AMBER),
            (" | ", "#4A3F55"),
            ("Healthcare", VIOLET_LT),
            (" | ", "#4A3F55"),
            ("Software Engineering", TEXT_SOFT),
        ],
    ),
    ("exploring", [("Autonomous ", TEXT_SOFT), ("Coding Agents", AMBER)]),
    ("building", [("Healthcare Intelligence", AMBER), (" Systems", TEXT_SOFT)]),
]


def terminal_svg() -> str:
    n_lines = len(TERMINAL_LINES) * 2 + 1  # 4 cmd + 4 out + 1 prompt cursor line
    content_h = n_lines * LINE_H + 14
    body_h = max(int(T_Y0 + content_h), 150)
    h = body_h + 6

    total = 11.6  # master loop seconds
    type_t = 0.62
    step = total / len(TERMINAL_LINES)

    clips, groups = [], []
    y = T_Y0
    for i, (cmd, out) in enumerate(TERMINAL_LINES):
        cmd_w = (len(cmd) + 2) * T_FS * 0.6
        f0 = (i * step) / total
        f1 = (i * step + type_t) / total
        keytimes = f"0;{f0:.4f};{f1:.4f};1"
        clips.append(
            f'  <clipPath id="tc{i}"><rect x="{T_X - 2}" y="{y - T_FS:.1f}" width="{cmd_w + 6:.1f}" height="20">'
            f'<animate attributeName="width" calcMode="linear" values="0;0;{cmd_w + 6:.1f};{cmd_w + 6:.1f}" '
            f'keyTimes="{keytimes}" dur="{total}s" repeatCount="indefinite"/></rect></clipPath>'
        )
        groups.append(
            f'  <g clip-path="url(#tc{i})"><text x="{T_X}" y="{y:.1f}" font-family="{MONO}" '
            f'font-size="{T_FS}"><tspan fill="{GOLD}">$</tspan>'
            f'<tspan fill="{TEXT}" dx="7">{escape(cmd)}</tspan></text></g>'
        )
        y += LINE_H
        fa = (i * step + type_t + 0.12) / total
        spans = "".join(f'<tspan fill="{fill}">{escape(t)}</tspan>' for t, fill in out)
        groups.append(
            f'  <g><text x="{T_X}" y="{y:.1f}" font-family="{MONO}" font-size="{T_FS}" '
            f'opacity="1"><animate attributeName="opacity" calcMode="discrete" '
            f'values="0;0;1;1" keyTimes="0;{fa:.4f};{min(fa + 0.002, 0.9999):.4f};1" '
            f'dur="{total}s" repeatCount="indefinite"/>{spans}</text></g>'
        )
        y += LINE_H

    prompt_y = y
    # fade the whole session out just before the loop restarts
    session_fade = (
        f'  <animate attributeName="opacity" calcMode="linear" '
        f'values="1;1;0" keyTimes="0;0.96;1" dur="{total}s" repeatCount="indefinite"/>'
    )
    prompt_cursor = (
        f'  <text x="{T_X}" y="{prompt_y:.1f}" font-family="{MONO}" font-size="{T_FS}">'
        f'<tspan fill="{GOLD}">$</tspan></text>'
        f'  <rect x="{T_X + 16}" y="{prompt_y - 12:.1f}" width="8" height="14" fill="{GOLD}">'
        f'<animate attributeName="opacity" values="1;0" calcMode="discrete" '
        f'dur="1.1s" repeatCount="indefinite"/></rect>'
    )

    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{TTW}" height="{h}" viewBox="0 0 {TTW} {h}" role="img" aria-label="Terminal: whoami - Arpit Nayan; interests - AI, Healthcare, Software Engineering; exploring - Autonomous Coding Agents; building - Healthcare Intelligence Systems">
  <defs>
    {lin_grad("thead", [(0, "#1D1528"), (1, "#110E19")])}
  </defs>

  <rect x="1" y="1" width="{TTW - 2}" height="{h - 2}" rx="14" fill="{BG_PANEL}" stroke="{STROKE}" stroke-width="1.5"/>
  <rect x="1.75" y="1.75" width="{TTW - 3.5}" height="43" rx="13" fill="url(#thead)"/>
  <rect x="1.75" y="24" width="{TTW - 3.5}" height="20" fill="url(#thead)"/>
  <circle cx="28" cy="23" r="6" fill="#FF5F57" opacity="0.92"/>
  <circle cx="50" cy="23" r="6" fill="#FEBC2E" opacity="0.92"/>
  <circle cx="72" cy="23" r="6" fill="#28C840" opacity="0.92"/>
  <text x="{TTW / 2}" y="27.5" text-anchor="middle" font-family="{MONO}" font-size="11.5" fill="{FAINT}">{escape(TERMINAL_TITLE)}</text>
  <line x1="1" y1="44" x2="{TTW - 1}" y2="44" stroke="{STROKE}" stroke-width="1"/>

<g opacity="1">
  {session_fade}
{chr(10).join(groups)}
{prompt_cursor}
</g>
</svg>
"""

# ----------------------------------------------------------------------------
# 3. Section divider
# ----------------------------------------------------------------------------

DW, DH = 896, 24


def divider_svg() -> str:
    x0, x1 = 148, DW - 148
    span = x1 - x0
    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{DW}" height="{DH}" viewBox="0 0 {DW} {DH}" role="img" aria-label="Section divider">
  <defs>
    {lin_grad("dline", [(0, GOLD, 0), (0.3, GOLD, 0.85), (0.7, AMBER, 0.85), (1, AMBER, 0)])}
  </defs>

  <rect x="{x0}" y="{DH / 2 - 0.8}" width="{span}" height="1.6" rx="0.8" fill="url(#dline)"/>
  <rect x="{x0}" y="{DH / 2 - 1.4}" width="64" height="2.8" rx="1.4" fill="{GOLD_LT}" opacity="0.5">
    <animate attributeName="x" calcMode="linear"
      values="{x0};{x1 - 64};{x0}" keyTimes="0;0.5;1"
      dur="6.5s" repeatCount="indefinite"/>
    <animate attributeName="opacity" calcMode="linear"
      values="0.05;0.55;0.05" keyTimes="0;0.5;1"
      dur="6.5s" repeatCount="indefinite"/>
  </rect>
  <circle cx="{DW / 2}" cy="{DH / 2}" r="2.2" fill="{GOLD_LT}" opacity="0.85"/>
</svg>
"""

# ----------------------------------------------------------------------------
# 4. Glassmorphism project cards + mantra strip
# ----------------------------------------------------------------------------

GW, GH = 896, 176          # card canvas
P_X, P_Y, P_W, P_H = 10, 10, 876, 156
P_RX = 16
MW, MH = 896, 76           # mantra strip canvas


def _glass_defs(accent: str) -> str:
    """Shared gradient/filter block for one glass card (IDs are per-document)."""
    return f"""  <defs>
    <filter id="gblur" x="-60%" y="-60%" width="220%" height="220%">
      <feGaussianBlur stdDeviation="26"/>
    </filter>
    <clipPath id="gclip"><rect x="{P_X}" y="{P_Y}" width="{P_W}" height="{P_H}" rx="{P_RX}"/></clipPath>
    {lin_grad("gtitle", [(0, GOLD_LT), (0.55, GOLD), (1, AMBER)])}
    {lin_grad("gpanel", [(0, "#FFFFFF", "0.09"), (1, "#FFFFFF", "0.025")], x1="0%", y1="0%", x2="0%", y2="100%")}
    {lin_grad("gsheen", [(0, "#FFFFFF", "0.16"), (1, "#FFFFFF", "0")], x1="0%", y1="0%", x2="0%", y2="100%")}
    {lin_grad("gborder", [(0, "#FFFFFF", "0.42"), (0.5, accent, "0.22"), (1, "#FFFFFF", "0.05")])}
  </defs>"""


def glass_card_svg(spec) -> str:
    """One frosted-glass project card: blurred accent blobs drifting behind
    a lit glass panel, gold gradient title, a one-line brief, a status pill
    and a quiet tech line."""
    name = escape(spec["name"])
    cat = escape(spec["category"])
    brief = escape(spec["brief"])
    tech = escape(spec["tech"])
    label = escape(spec["status"])
    aria = f"{name} - {cat}"
    dot, accent = spec["dot"], spec["accent"]
    chip_w = round(len(spec["status"]) * 6.8 + 40)
    chip_x = GW - 26 - chip_w
    blobs = []
    for col, cx, cy, r, op, tx, ty, dur in spec["blobs"]:
        blobs.append(
            f'    <circle cx="{cx}" cy="{cy}" r="{r}" fill="{col}" opacity="{op}" filter="url(#gblur)">'
            f'<animateTransform attributeName="transform" type="translate" '
            f'values="0 0; {tx} {ty}; 0 0" dur="{dur}s" repeatCount="indefinite"/></circle>'
        )
    body = "\n".join(blobs)
    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{GW}" height="{GH}" viewBox="0 0 {GW} {GH}" role="img" aria-label="{aria}">
{_glass_defs(accent)}

  <rect x="{P_X}" y="{P_Y}" width="{P_W}" height="{P_H}" rx="{P_RX}" fill="{BG_PANEL}"/>
  <g clip-path="url(#gclip)">
{body}
    <rect x="{P_X}" y="{P_Y}" width="{P_W}" height="64" fill="url(#gsheen)"/>
    <g transform="skewX(-14)"><rect x="-150" y="-20" width="120" height="230" fill="#FFFFFF" opacity="0.05"><animateTransform attributeName="transform" type="translate" values="0 0; 1220 0" dur="9s" repeatCount="indefinite"/></rect></g>
  </g>
  <rect x="{P_X + 0.6}" y="{P_Y + 0.6}" width="{P_W - 1.2}" height="{P_H - 1.2}" rx="{P_RX}" fill="none" stroke="url(#gborder)" stroke-width="1.2"/>
  <circle cx="56" cy="62" r="23" fill="#FFFFFF" fill-opacity="0.08" stroke="#FFFFFF" stroke-opacity="0.22"/>
  <text x="56" y="70" text-anchor="middle" font-family="{MONO}" font-size="21" font-weight="700" fill="url(#gtitle)">{spec["mono"]}</text>
  <text x="94" y="54" font-family="{MONO}" font-size="19" font-weight="700" letter-spacing="0.4" fill="url(#gtitle)">{name}</text>
  <text x="94" y="72" font-family="{MONO}" font-size="9.5" letter-spacing="2.2" fill="{accent}">{cat}</text>
  <text x="94" y="100" font-family="{MONO}" font-size="12.5" fill="{TEXT_SOFT}">{brief}</text>
  <line x1="94" y1="118" x2="{GW - 90}" y2="118" stroke="#FFFFFF" stroke-opacity="0.07"/>
  <text x="94" y="141" font-family="{MONO}" font-size="10.5" fill="{FAINT}">{tech}</text>
  <rect x="{chip_x}" y="24" width="{chip_w}" height="24" rx="12" fill="#FFFFFF" fill-opacity="0.07" stroke="#FFFFFF" stroke-opacity="0.16"/>
  <circle cx="{chip_x + 15}" cy="36" r="3.4" fill="{dot}"/>
  <text x="{chip_x + 26}" y="39.5" font-family="{MONO}" font-size="9.5" letter-spacing="1.6" fill="{TEXT_SOFT}">{label}</text>
</svg>
"""


def mantra_svg() -> str:
    """Frosted strip carrying the personal mantra in a slowly breathing
    gold gradient."""
    return f"""{GENERATED_NOTE}
<svg xmlns="http://www.w3.org/2000/svg" width="{MW}" height="{MH}" viewBox="0 0 {MW} {MH}" role="img" aria-label="Personal mantra - learn relentlessly, build honestly, iterate">
  <defs>
    {lin_grad("mpanel", [(0, "#FFFFFF", "0.08"), (1, "#FFFFFF", "0.02")], x1="0%", y1="0%", x2="0%", y2="100%")}
    {lin_grad("mborder", [(0, "#FFFFFF", "0.35"), (0.5, GOLD, "0.18"), (1, "#FFFFFF", "0.05")])}
    <linearGradient id="mtext" x1="0%" y1="0%" x2="100%" y2="0%">
      <stop offset="0" stop-color="{GOLD_LT}"><animate attributeName="stop-color" values="{GOLD_LT};{ORANGE};{GOLD_LT}" dur="7s" repeatCount="indefinite"/></stop>
      <stop offset="1" stop-color="{AMBER}"><animate attributeName="stop-color" values="{AMBER};{GOLD_LT};{AMBER}" dur="7s" repeatCount="indefinite"/></stop>
    </linearGradient>
  </defs>
  <rect x="{P_X}" y="{P_Y}" width="{P_W}" height="56" rx="14" fill="{BG_PANEL}"/>
  <rect x="{P_X}" y="{P_Y}" width="{P_W}" height="56" rx="14" fill="url(#mpanel)"/>
  <rect x="{P_X + 0.6}" y="{P_Y + 0.6}" width="{P_W - 1.2}" height="54.8" rx="14" fill="none" stroke="url(#mborder)" stroke-width="1.2"/>
  <circle cx="90" cy="38" r="2.4" fill="{GOLD}" opacity="0.9"><animate attributeName="opacity" values="0.4;0.95;0.4" dur="3.5s" repeatCount="indefinite"/></circle>
  <circle cx="806" cy="38" r="2.4" fill="{GOLD}" opacity="0.9"><animate attributeName="opacity" values="0.4;0.95;0.4" dur="3.5s" begin="1.75s" repeatCount="indefinite"/></circle>
  <text x="{MW / 2}" y="43" text-anchor="middle" font-family="{MONO}" font-size="15.5" font-weight="600" letter-spacing="1.2" fill="url(#mtext)">learn relentlessly &#183; build honestly &#183; iterate</text>
</svg>
"""


# (file, monogram, name, category, one-line brief, tech line, status label,
#  status dot, accent, drifting background blobs)
PROJECTS: list[dict] = []


def render_project_cards(only: str | None = None) -> None:
    for spec in PROJECTS:
        if only is not None and spec["file"] != only:
            continue
        (ASSETS / spec["file"]).write_text(glass_card_svg(spec), encoding="utf-8")
        print(f"wrote  assets/{spec['file']:26}")


# ----------------------------------------------------------------------------
# main
# ----------------------------------------------------------------------------
FILES = {
    "typing.svg": typing_svg,
    "terminal.svg": terminal_svg,
    "divider.svg": divider_svg,
    "mantra.svg": mantra_svg,
}


def main() -> None:
    ASSETS.mkdir(exist_ok=True)
    for name, fn in FILES.items():
        svg = fn()
        (ASSETS / name).write_text(svg, encoding="utf-8")
        print(f"wrote  assets/{name:20} {len(svg):6d} bytes")
    render_project_cards()


if __name__ == "__main__":
    main()
